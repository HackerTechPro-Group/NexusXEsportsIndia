#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';

const ROOT_DIR = path.resolve(import.meta.dirname, '..', '..');
const ENV_LOCAL_PATH = path.join(ROOT_DIR, '.env.local');
const DEV_VARS_PATH = path.join(ROOT_DIR, 'worker', '.dev.vars');

const ADMIN_ROUTE_DOMAIN_PREFIX = 'nexusx:admin-route:v1:';
const BLOCKED_PREDICTABLE_SLUGS = new Set([
  '',
  'admin',
  'dashboard',
  'administrator',
  'login',
  'portal',
  'signin',
  'sign-in',
  'wp-admin',
  'gamingclub',
]);

export function validatePrivateAdminSlug(rawInput) {
  const normalized = String(rawInput ?? '')
    .trim()
    .replace(/^\/+|\/+$/g, '')
    .toLowerCase();

  if (normalized.length < 8 || normalized.length > 64) {
    return {
      valid: false,
      normalized,
      error: 'Private Admin path must be between 8 and 64 characters (excluding leading /).',
    };
  }
  if (!/^[a-z0-9][a-z0-9/_-]*[a-z0-9]$/.test(normalized) || normalized.includes('//')) {
    return {
      valid: false,
      normalized,
      error: 'Private Admin path may use only lowercase letters, numbers, hyphens, underscores, or single slashes.',
    };
  }
  const firstSegment = normalized.split('/')[0] ?? '';
  if (BLOCKED_PREDICTABLE_SLUGS.has(normalized) || BLOCKED_PREDICTABLE_SLUGS.has(firstSegment)) {
    return {
      valid: false,
      normalized,
      error: `Refusing predictable or retired path "/${normalized}". Choose a unique private slug.`,
    };
  }
  return { valid: true, normalized };
}

export function computeRouteDigest(normalizedSlug) {
  return crypto
    .createHash('sha256')
    .update(`${ADMIN_ROUTE_DOMAIN_PREFIX}${normalizedSlug}`, 'utf8')
    .digest('hex');
}

function readExistingOptionalGithubVars(filePath) {
  if (!fs.existsSync(filePath)) return [];
  const raw = fs.readFileSync(filePath, 'utf8');
  return raw
    .split(/\r?\n/)
    .filter((line) => /^(GITHUB_APP_ID|GITHUB_APP_INSTALLATION_ID|GITHUB_APP_PRIVATE_KEY)=/.test(line.trim()));
}

async function promptForPrivateSlug() {
  const argIdx = process.argv.indexOf('--path');
  if (argIdx !== -1 && process.argv[argIdx + 1]) {
    const check = validatePrivateAdminSlug(process.argv[argIdx + 1]);
    if (!check.valid) {
      throw new Error(check.error);
    }
    return check.normalized;
  }

  const rl = readline.createInterface({ input, output });
  try {
    console.log('\nNexusX Esports India — Secure Local Admin Setup');
    console.log('------------------------------------------------');
    console.log(
      'Enter your custom private Admin URL path (min 8 chars, e.g. /nx-ops-vault-924).'
    );
    console.log(
      'Only its SHA-256 digest is written to .env.local; fresh owner credentials will be\ncreated interactively in the browser via Initial Owner Setup.\n'
    );

    while (true) {
      const answer = await rl.question('Custom Private Admin Path: ');
      const check = validatePrivateAdminSlug(answer);
      if (check.valid) {
        return check.normalized;
      }
      console.error(`Invalid path: ${check.error}\n`);
    }
  } finally {
    rl.close();
  }
}

async function main() {
  const normalizedSlug = await promptForPrivateSlug();
  const routeHash = computeRouteDigest(normalizedSlug);
  const sessionSecret = crypto.randomBytes(32).toString('hex');
  const setupToken = crypto.randomBytes(24).toString('hex');

  const envLocalContent = [
    '# Local-only Admin portal configuration (gitignored - NEVER commit)',
    '# Generated by `npm run setup:local`. Plaintext private route is not stored on disk.',
    `VITE_ADMIN_PATH_HASH=${routeHash}`,
    'VITE_ADMIN_API_URL=http://localhost:8787',
    '',
  ].join('\n');

  const preservedGithubLines = readExistingOptionalGithubVars(DEV_VARS_PATH);
  const devVarsLines = [
    '# Strictly local development Worker config (gitignored - NEVER commit)',
    '# Generated with fresh CSPRNG tokens. No default Admin ID or password is stored here.',
    'ENVIRONMENT=development',
    'ALLOWED_ORIGINS=http://localhost:5173,http://127.0.0.1:5173',
    `SESSION_SECRET=${sessionSecret}`,
    `ADMIN_SETUP_TOKEN=${setupToken}`,
    ...preservedGithubLines,
    '',
  ];

  fs.writeFileSync(ENV_LOCAL_PATH, envLocalContent, { mode: 0o600 });
  fs.writeFileSync(DEV_VARS_PATH, devVarsLines.join('\n'), { mode: 0o600 });

  console.log('\nLocal security files updated (.env.local & worker/.dev.vars):');
  console.log(`- Private Route Hash : ${routeHash}`);
  console.log(`- Local Admin URL    : http://localhost:5173/#/${normalizedSlug}`);
  console.log(`- One-Time Setup Token (enter in browser Initial Owner Setup): ${setupToken}`);
  console.log('\nNext Steps:');
  console.log('1. Start frontend: npm run dev -- --port 5173');
  console.log('2. Start worker  : cd worker && npx wrangler dev --port 8787');
  console.log(`3. Open http://localhost:5173/#/${normalizedSlug} and complete Initial Owner Setup.`);
  console.log('4. Remove ADMIN_SETUP_TOKEN from worker/.dev.vars once setup is done.\n');
}

const isEntrypoint =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename);
if (isEntrypoint) {
  main().catch((err) => {
    console.error(`Setup aborted: ${err instanceof Error ? err.message : String(err)}`);
    process.exit(1);
  });
}
